"""Request authentication for the loopback-only backend.

Every request must carry the per-launch token generated by the Electron main process,
and a Host header that names the loopback interface (guards against DNS rebinding).
"""

from __future__ import annotations

import hmac

from starlette.responses import JSONResponse
from starlette.types import ASGIApp, Receive, Scope, Send

TOKEN_HEADER = b"x-transformo-token"


class LocalAuthMiddleware:
    def __init__(self, app: ASGIApp, *, token: str, port: int) -> None:
        self.app = app
        self._token = token.encode()
        self._allowed_hosts = {f"127.0.0.1:{port}".encode(), f"localhost:{port}".encode()}

    async def __call__(self, scope: Scope, receive: Receive, send: Send) -> None:
        if scope["type"] != "http":
            await self.app(scope, receive, send)
            return

        headers = dict(scope["headers"])
        if headers.get(b"host") not in self._allowed_hosts:
            await JSONResponse({"detail": "Invalid host"}, status_code=400)(scope, receive, send)
            return

        supplied = headers.get(TOKEN_HEADER, b"")
        if not hmac.compare_digest(supplied, self._token):
            await JSONResponse({"detail": "Unauthorized"}, status_code=401)(scope, receive, send)
            return

        await self.app(scope, receive, send)
